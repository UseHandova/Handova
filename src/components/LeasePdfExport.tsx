/**
 * LeasePdfExport — generates a downloadable lease certificate PDF (HTML-to-print approach).
 * Opens a printable window with the lease details, escrow tx hash, and RentFlow branding.
 * No external PDF library needed — uses the browser's built-in print dialog.
 */

import { useState } from 'react';
import { motion } from 'framer-motion';
import { FileText, Download, Loader2, ExternalLink } from 'lucide-react';
import { useLang } from '@/lib/LangContext';
import { formatNaira } from '@/lib/naira';
import { buildTxExplorerUrl } from '@/onchain-facts';

export interface LeaseData {
  escrowId: string;
  property: string;
  address: string;
  landlordName?: string;
  tenantName?: string;
  rentUsdc: number;
  depositUsdc: number;
  startDate: string;
  txHash?: string;
}

interface Props {
  lease: LeaseData;
  onClose?: () => void;
}

export default function LeasePdfExport({ lease, onClose }: Props) {
  const { t } = useLang();
  const [generating, setGenerating] = useState(false);

  function generatePdf() {
    setGenerating(true);
    const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<title>RentFlow Lease Certificate — Escrow #${lease.escrowId}</title>
<style>
  body { font-family: 'Segoe UI', sans-serif; max-width: 700px; margin: 40px auto; color: #0c2218; }
  .header { text-align: center; border-bottom: 3px solid #0a6638; padding-bottom: 20px; margin-bottom: 32px; }
  .logo { font-size: 28px; font-weight: 900; color: #0a6638; letter-spacing: -0.04em; }
  .cert-title { font-size: 16px; color: #44695a; margin-top: 4px; }
  .section { margin-bottom: 24px; }
  .section h2 { font-size: 11px; text-transform: uppercase; letter-spacing: 0.1em; color: #44695a; margin-bottom: 8px; }
  .row { display: flex; justify-content: space-between; padding: 8px 0; border-bottom: 1px solid #e8f5ee; font-size: 13px; }
  .row .label { color: #44695a; }
  .row .value { font-weight: 600; color: #0c2218; }
  .badge { display: inline-block; padding: 4px 12px; border-radius: 99px; font-size: 11px; font-weight: 700; background: #e6f4ec; color: #0a6638; }
  .hash { font-family: monospace; font-size: 11px; color: #44695a; word-break: break-all; margin-top: 8px; }
  .footer { text-align: center; margin-top: 40px; font-size: 11px; color: #7a9e8a; }
  @media print { body { margin: 0; } }
</style>
</head>
<body>
<div class="header">
  <div class="logo">RentFlow</div>
  <div class="cert-title">Official Lease Certificate — Recorded Onchain</div>
  <div style="margin-top:8px"><span class="badge">Verified by Smart Contract</span></div>
</div>

<div class="section">
  <h2>Property Details</h2>
  <div class="row"><span class="label">Property</span><span class="value">${lease.property}</span></div>
  <div class="row"><span class="label">Address</span><span class="value">${lease.address}</span></div>
  ${lease.landlordName ? `<div class="row"><span class="label">Landlord</span><span class="value">${lease.landlordName}</span></div>` : ''}
  ${lease.tenantName ? `<div class="row"><span class="label">Tenant</span><span class="value">${lease.tenantName}</span></div>` : ''}
</div>

<div class="section">
  <h2>Financial Terms</h2>
  <div class="row"><span class="label">Annual Rent</span><span class="value">${formatNaira(lease.rentUsdc)} (${lease.rentUsdc.toFixed(2)} USDC)</span></div>
  <div class="row"><span class="label">Security Deposit</span><span class="value">${formatNaira(lease.depositUsdc)} (${lease.depositUsdc.toFixed(2)} USDC)</span></div>
  <div class="row"><span class="label">Lease Start</span><span class="value">${lease.startDate}</span></div>
</div>

<div class="section">
  <h2>Blockchain Record</h2>
  <div class="row"><span class="label">Escrow ID</span><span class="value">#${lease.escrowId}</span></div>
  <div class="row"><span class="label">Chain</span><span class="value">Arc Testnet (Chain ID: 5042002)</span></div>
  ${lease.txHash ? `<div class="row"><span class="label">Transaction Hash</span></div><div class="hash">${lease.txHash}</div>` : ''}
</div>

<div class="footer">
  This certificate is backed by an immutable smart contract on the Arc blockchain. Zero agent fees. Zero hidden charges.<br/>
  Generated by RentFlow — ${new Date().toLocaleDateString('en-NG', { dateStyle: 'long' })}
</div>
</body>
</html>`;

    const w = window.open('', '_blank', 'width=800,height=900');
    if (w) {
      w.document.write(html);
      w.document.close();
      setTimeout(() => { w.print(); setGenerating(false); }, 600);
    } else {
      setGenerating(false);
    }
  }

  const explorerUrl = lease.txHash ? buildTxExplorerUrl(5042002, lease.txHash) : null;

  return (
    <div className="rounded-3xl p-5 space-y-4"
      style={{ background: 'var(--glass-card)', backdropFilter: 'blur(24px)', WebkitBackdropFilter: 'blur(24px)', border: '1px solid var(--glass-border)', boxShadow: 'var(--shadow-card)' }}>
      <div className="flex items-center gap-3">
        <div className="w-10 h-10 rounded-2xl flex items-center justify-center"
          style={{ background: 'var(--accent-soft)' }}>
          <FileText className="w-5 h-5" style={{ color: 'var(--accent)' }} />
        </div>
        <div>
          <p className="font-bold text-sm" style={{ color: 'var(--ink)' }}>{t('lease_pdf_title')}</p>
          <p className="text-xs" style={{ color: 'var(--muted)' }}>{t('lease_pdf_sub')}</p>
        </div>
      </div>

      <div className="space-y-2 text-xs" style={{ color: 'var(--muted)' }}>
        <div className="flex justify-between py-1.5 border-b" style={{ borderColor: 'var(--border)' }}>
          <span>Escrow ID</span><span className="font-semibold mono" style={{ color: 'var(--ink)' }}>#{lease.escrowId}</span>
        </div>
        <div className="flex justify-between py-1.5 border-b" style={{ borderColor: 'var(--border)' }}>
          <span>Rent</span><span className="font-semibold tabular-nums" style={{ color: 'var(--ink)' }}>{formatNaira(lease.rentUsdc)}/yr</span>
        </div>
        <div className="flex justify-between py-1.5" >
          <span>Start</span><span className="font-semibold" style={{ color: 'var(--ink)' }}>{lease.startDate}</span>
        </div>
      </div>

      <div className="flex gap-2">
        <motion.button whileTap={{ scale: 0.96 }} onClick={generatePdf} disabled={generating}
          className="flex-1 py-3 rounded-2xl font-semibold text-white text-sm flex items-center justify-center gap-2"
          style={{ background: generating ? 'var(--subtle)' : 'linear-gradient(135deg, var(--accent) 0%, #14a85a 100%)', boxShadow: generating ? 'none' : '0 4px 16px var(--accent-glow)' }}>
          {generating ? <><Loader2 className="w-3.5 h-3.5 animate-spin" /> {t('generating_pdf')}</> : <><Download className="w-3.5 h-3.5" /> {t('download_lease')}</>}
        </motion.button>
        {explorerUrl && (
          <a href={explorerUrl} target="_blank" rel="noopener noreferrer"
            className="w-12 h-12 rounded-2xl flex items-center justify-center shrink-0"
            style={{ background: 'var(--surface-strong)', border: '1px solid var(--border)' }}>
            <ExternalLink className="w-4 h-4" style={{ color: 'var(--muted)' }} />
          </a>
        )}
      </div>
      {onClose && (
        <button onClick={onClose} className="w-full text-xs text-center py-1" style={{ color: 'var(--subtle)' }}>Close</button>
      )}
    </div>
  );
}
